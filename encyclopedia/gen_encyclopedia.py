def call_mimo_api(prompt, max_tokens=8000):
    """Call MiMo API to generate content"""
    headers = {
        "Authorization": f"Bearer {API_KEY}",
        "Content-Type": "application/json"
    }
    payload = {
        "model": MODEL,
        "messages": [
            {"role": "system", "content": "你是一个百科全书内容生成专家。你生成的内容准确、丰富、有趣。只输出JSON数组，不要任何其他文字。"},
            {"role": "user", "content": prompt}
        ],
        "max_tokens": max_tokens,
        "temperature": 0.7
    }
    try:
        resp = requests.post(f"{BASE_URL}/chat/completions", json=payload, headers=headers, timeout=120)
        resp.raise_for_status()
        return resp.json()["choices"][0]["message"]["content"]
    except Exception as e:
        print(f"  API error: {e}")
        return None

def parse_json_from_text(text):
    """Extract JSON array from API response text"""
    if not text:
        return None
    # Remove markdown code blocks
    text = re.sub(r'```json\s*', '', text)
    text = re.sub(r'```\s*', '', text)
    text = text.strip()
    
    # Try direct parse first
    try:
        result = json.loads(text)
        if isinstance(result, list):
            return result
    except:
        pass
    
    # Try to find JSON array in the response
    match = re.search(r'\[.*\]', text, re.DOTALL)
    if match:
        raw = match.group()
        # Remove trailing commas
        raw = re.sub(r',\s*}', '}', raw)
        raw = re.sub(r',\s*]', ']', raw)
        try:
            return json.loads(raw)
        except json.JSONDecodeError:
            # Try line-by-line fixing
            pass
    
    # Last resort: try to find array boundaries manually
    start = text.find('[')
    end = text.rfind(']')
    if start != -1 and end != -1 and end > start:
        raw = text[start:end+1]
        raw = re.sub(r',\s*}', '}', raw)
        raw = re.sub(r',\s*]', ']', raw)
        try:
            return json.loads(raw)
        except:
            pass
    
    return None

def get_existing_ids(filepath):
    """Load existing IDs from a category JSON file"""
    try:
        with open(filepath, 'r') as f:
            data = json.load(f)
        return set(e['id'] for e in data)
    except:
        return set()

def load_existing_data(filepath):
    """Load existing category data"""
    try:
        with open(filepath, 'r') as f:
            return json.load(f)
    except:
        return []

def generate_batch(cat_key, cat_name, id_prefix, id_digits, topics_batch, start_num):
    """Generate a batch of encyclopedia entries"""
    topics_str = "、".join(topics_batch)
    example_id = f"{id_prefix}-{start_num:0{id_digits}d}"
    prompt = f"""为"{cat_name}"百科生成{len(topics_batch)}个词条，主题：{topics_str}

JSON格式：
[{{"id":"{example_id}","title":"标题","category":"{cat_key}","categoryName":"{cat_name}","summary":"30-60字摘要","content":"200-400字详细内容","keyFacts":["事实1","事实2","事实3"],"relatedIds":["id1","id2"],"funFact":"冷知识","era":"时期","importance":3}}]

id编号从{start_num}开始递增。只输出JSON数组。"""

    result = call_mimo_api(prompt)
    if not result:
        return []
    
    entries = parse_json_from_text(result)
    if not entries:
        print(f"  Failed to parse JSON from response (len={len(result)})")
        # Save raw response for debugging
        with open(f"/tmp/debug_{cat_key}_{start_num}.txt", 'w') as f:
            f.write(result)
        return []
    
    # Validate and fix entries
    valid_entries = []
    for e in entries:
        if not isinstance(e, dict):
            continue
        required_keys = ['id', 'title', 'category', 'categoryName', 'summary', 'content', 'keyFacts', 'relatedIds', 'funFact', 'era', 'importance']
        if all(k in e for k in required_keys):
            # Ensure proper types
            if not isinstance(e['keyFacts'], list):
                e['keyFacts'] = [str(e['keyFacts'])]
            if not isinstance(e['relatedIds'], list):
                e['relatedIds'] = [str(e['relatedIds'])]
            if not isinstance(e['importance'], int):
                try:
                    e['importance'] = int(e['importance'])
                except:
                    e['importance'] = 3
            valid_entries.append(e)
    
    return valid_entries

def update_index():
    """Regenerate index.json from all category files"""
    index = []
    categories = ['biology', 'chemistry', 'economics', 'geography', 'history',
                  'medicine', 'military', 'philosophy', 'physics', 'technology']
    
    for cat_key in categories:
        filepath = os.path.join(DATA_DIR, f"{cat_key}.json")
        try:
            with open(filepath, 'r') as f:
                data = json.load(f)
            for e in data:
                index.append({
                    "id": e["id"],
                    "title": e["title"],
                    "category": e["category"],
                    "categoryName": e["categoryName"],
                    "summary": e["summary"]
                })
        except Exception as ex:
            print(f"Error reading {cat_key}: {ex}")
    
    # Write index
    index_path = os.path.join(DATA_DIR, "index.json")
    with open(index_path, 'w', encoding='utf-8') as f:
        json.dump(index, f, ensure_ascii=False, indent=2)
    
    # Backup
    backup_path = os.path.join(BACKUP_DIR, "index.json")
    with open(backup_path, 'w', encoding='utf-8') as f:
        json.dump(index, f, ensure_ascii=False, indent=2)
    
    print(f"\nIndex updated: {len(index)} total entries")

def process_category(cat_key, cat_name, id_prefix, id_digits, current_count, topics):
    """Process a single category - generate and append entries"""
    target = 500
    
    filepath = os.path.join(DATA_DIR, f"{cat_key}.json")
    existing_data = load_existing_data(filepath)
    actual_count = len(existing_data)
    needed = target - actual_count
    
    if needed <= 0:
        print(f"[{cat_name}] Already at {actual_count}, skipping", flush=True)
        return
    
    print(f"\n{'='*60}", flush=True)
    print(f"[{cat_name}] Current: {actual_count}, Target: {target}, Need: {needed}", flush=True)
    print(f"{'='*60}", flush=True)
    existing_ids = set(e['id'] for e in existing_data)
    
    # Calculate starting ID number
    max_num = 0
    for eid in existing_ids:
        try:
            num = int(eid.split('-')[1])
            max_num = max(max_num, num)
        except:
            pass
    
    batch_size = 10  # Smaller batches for reliability
    total_generated = 0
    topic_idx = 0
    retries = 0
    max_retries = 10
    
    while total_generated < needed and retries < max_retries:
        batch_num = max_num + total_generated + 1
        remaining = needed - total_generated
        current_batch_size = min(batch_size, remaining)
        
        # Get topics for this batch
        if topic_idx < len(topics):
            batch_topics = topics[topic_idx:topic_idx + current_batch_size]
            topic_idx += current_batch_size
        else:
            batch_topics = [f"{cat_name}专题{i+1}" for i in range(current_batch_size)]
        
        print(f"  Batch #{total_generated//batch_size + 1} at {id_prefix}-{batch_num:0{id_digits}d}, size={current_batch_size}...", flush=True)
        
        entries = generate_batch(cat_key, cat_name, id_prefix, id_digits, batch_topics, batch_num)
        
        if not entries:
            retries += 1
            print(f"  Retry {retries}/{max_retries}...", flush=True)
            time.sleep(5)
            continue
        
        retries = 0  # Reset on success
        
        # Filter out duplicates and reassign IDs
        new_entries = []
        next_id = batch_num
        for e in entries:
            new_id = f"{id_prefix}-{next_id:0{id_digits}d}"
            while new_id in existing_ids:
                next_id += 1
                new_id = f"{id_prefix}-{next_id:0{id_digits}d}"
            e['id'] = new_id
            new_entries.append(e)
            existing_ids.add(new_id)
            next_id += 1
        
        existing_data.extend(new_entries)
        total_generated += len(new_entries)
        
        print(f"  Got {len(new_entries)} entries. Progress: {total_generated}/{needed}", flush=True)
        
        # Save incrementally
        with open(filepath, 'w', encoding='utf-8') as f:
            json.dump(existing_data, f, ensure_ascii=False, indent=2)
        
        backup_path = os.path.join(BACKUP_DIR, f"{cat_key}.json")
        with open(backup_path, 'w', encoding='utf-8') as f:
            json.dump(existing_data, f, ensure_ascii=False, indent=2)
        
        time.sleep(2)
    
    if retries >= max_retries:
        print(f"  [{cat_name}] Stopped after {max_retries} retries. Progress: {total_generated}/{needed}", flush=True)
    print(f"  [{cat_name}] Done! Final count: {len(existing_data)}", flush=True)

def main():
    print("=" * 60, flush=True)
    print("DK百科批量扩充 - MiMo API 生成", flush=True)
    print("=" * 60, flush=True)
    
    start_time = time.time()
    
    for cat_key, cat_name, id_prefix, id_digits, current_count, topics in CATEGORIES:
        needed = 500 - current_count
        if needed > 0:
            process_category(cat_key, cat_name, id_prefix, id_digits, current_count, topics)
    
    elapsed = time.time() - start_time
    
    print("\n" + "=" * 60, flush=True)
    print("Updating index.json...", flush=True)
    update_index()
    
    print(f"\nTotal time: {elapsed/60:.1f} minutes", flush=True)
    print("=" * 60, flush=True)
    print("All categories expanded to 500 entries!", flush=True)
    print("=" * 60, flush=True)

if __name__ == "__main__":
    main()
