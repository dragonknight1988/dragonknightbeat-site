def call_mimo(system_prompt, user_prompt):
    headers = {"Authorization": f"Bearer {API_KEY}", "Content-Type": "application/json"}
    payload = {
        "model": MODEL,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt}
        ],
        "max_tokens": 8000,
        "temperature": 0.75
    }
    try:
        resp = requests.post(f"{BASE_URL}/chat/completions", headers=headers, json=payload, timeout=300)
        resp.raise_for_status()
        data = resp.json()
        content = data["choices"][0]["message"]["content"]
        usage = data.get("usage", {})
        print(f"  📝 Token: {usage.get('total_tokens', '?')}")
        return content
    except Exception as e:
        print(f"  ❌ API失败: {e}")
        return None

def parse_entries(text, prefix, cat_id, cat_name, start_idx):
    """解析API返回的JSON数组"""
    clean = text.strip()
    if clean.startswith("```json"): clean = clean[7:]
    if clean.startswith("```"): clean = clean[3:]
    if clean.endswith("```"): clean = clean[:-3]
    clean = clean.strip()
    
    start = clean.find("[")
    end = clean.rfind("]") + 1
    if start < 0 or end <= start:
        return None
    
    try:
        entries = json.loads(clean[start:end])
        for i, e in enumerate(entries):
            idx = start_idx + i
            if not e.get("id"):
                e["id"] = f"{prefix}-{idx:03d}"
            if not e.get("category"):
                e["category"] = cat_id
            if not e.get("categoryName"):
                e["categoryName"] = cat_name
        return entries
    except json.JSONDecodeError:
        return None

def expand_category(cat_id, cat_name, prefix):
    """扩充单个分类到500条"""
    filepath = os.path.join(OUT_DIR, f"{cat_id}.json")
    
    # 读取已有数据
    existing = []
    if os.path.exists(filepath):
        with open(filepath, "r") as f:
            existing = json.load(f)
    
    existing_count = len(existing)
    print(f"\n{'='*50}")
    print(f"📚 {cat_name}: 已有 {existing_count} 条，目标 {TARGET_PER_CAT} 条")
    print(f"{'='*50}")
    
    if existing_count >= TARGET_PER_CAT:
        print(f"  ⏭️ 已达标，跳过")
        return existing
    
    # 获取已有标题集合，避免重复
    existing_titles = {e["title"] for e in existing}
    
    # 获取子话题列表
    topics = EXPAND_TOPICS.get(cat_id, [])
    if not topics:
        print(f"  ⚠️ 无子话题列表，跳过")
        return existing
    
    # 过滤掉已有的话题
    new_topics = [t for t in topics if t not in existing_titles]
    needed = TARGET_PER_CAT - existing_count
    
    print(f"  📝 需要新增 {needed} 条，可用子话题 {len(new_topics)} 个")
    
    all_new = []
    batch_num = 0
    
    while len(all_new) < needed and new_topics:
        batch = new_topics[:BATCH_SIZE]
        new_topics = new_topics[BATCH_SIZE:]
        batch_num += 1
        start_idx = existing_count + len(all_new) + 1
        
        topics_text = "、".join(batch)
        system_prompt = f"""你是百科全书编辑。请为以下{cat_name}领域的{len(batch)}个词条生成百科内容。

⚠️ 铁律：
1. 内容必须准确真实，不能编造
2. 用中文
3. 直接输出JSON数组，不要代码块
4. 每个词条格式：
{{
  "id": "{prefix}-{start_idx:03d}",
  "title": "词条名",
  "category": "{cat_id}",
  "categoryName": "{cat_name}",
  "summary": "一句话概述（30-60字）",
  "content": "详细内容（150-300字）",
  "keyFacts": ["事实1", "事实2", "事实3"],
  "relatedIds": ["其他词条id"],
  "funFact": "一个有趣的冷知识",
  "importance": 4
}}

importance: 1-5（5最重要）
id格式: {prefix}-{start_idx:03d} 到 {prefix}-{start_idx+len(batch)-1:03d}
relatedIds: 至少引用2个同分类或跨分类的词条id
⚠️ 不要生成以下已有词条：{', '.join(list(existing_titles)[:20])}..."""

        print(f"\n  🔄 批次 {batch_num}: {', '.join(batch[:5])}...")
        result = call_mimo(system_prompt, f"请为以下{cat_name}词条生成百科内容：\n{topics_text}")
        
        if not result:
            print(f"  ❌ 批次 {batch_num} 失败，跳过")
            continue
        
        entries = parse_entries(result, prefix, cat_id, cat_name, start_idx)
        if entries:
            # 去重
            new_entries = [e for e in entries if e["title"] not in existing_titles]
            all_new.extend(new_entries)
            for e in new_entries:
                existing_titles.add(e["title"])
            print(f"  ✅ 批次 {batch_num}: 生成 {len(new_entries)} 条 (累计 {len(all_new)}/{needed})")
        else:
            print(f"  ❌ 批次 {batch_num}: JSON解析失败")
        
        time.sleep(1)
    
    # 合并并保存
    final = existing + all_new[:needed]
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(final, f, ensure_ascii=False, indent=2)
    print(f"\n  💾 {cat_name}: {existing_count} → {len(final)} 条")
    return final

def rebuild_index():
    """重建索引文件"""
    all_entries = []
    for f in os.listdir(OUT_DIR):
        if f.endswith(".json") and f != "index.json":
            try:
                data = json.load(open(os.path.join(OUT_DIR, f)))
                all_entries.extend(data)
            except:
                pass
    
    index = []
    for e in all_entries:
        index.append({
            "id": e["id"],
            "title": e["title"],
            "category": e["category"],
            "categoryName": e["categoryName"],
            "summary": e.get("summary", "")
        })
    
    index_path = os.path.join(OUT_DIR, "index.json")
    with open(index_path, "w", encoding="utf-8") as f:
        json.dump(index, f, ensure_ascii=False, indent=2)
    print(f"\n📋 索引已重建: {len(index)} 条")

